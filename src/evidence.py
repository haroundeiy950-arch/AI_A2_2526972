"""Generate the evidence PDFs: test log and signed declaration template."""
from __future__ import annotations

import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import config

STYLES = getSampleStyleSheet()
BODY = ParagraphStyle("Body", parent=STYLES["BodyText"], fontSize=10, leading=14)
MONO = ParagraphStyle("Mono", parent=STYLES["BodyText"], fontName="Courier", fontSize=6.4, leading=8.2)
HEAD = ParagraphStyle("Head", parent=STYLES["Heading1"], fontSize=15, spaceAfter=10)


def _header_lines(title: str) -> list:
    return [
        Paragraph(title, HEAD),
        Paragraph(
            f"Student: <b>{config.FULL_NAME}</b> | Registration: <b>{config.REGISTRATION_NUMBER}</b> "
            f"| Username: {config.INSTITUTIONAL_USERNAME} | Verification code: "
            f"<b>{config.VERIFICATION_CODE}</b>",
            BODY,
        ),
        Spacer(1, 8),
    ]


def _footer_note() -> Paragraph:
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    return Paragraph(
        f"Generated by src/evidence.py on {stamp} UTC. "
        f"Verification code {config.VERIFICATION_CODE}.",
        ParagraphStyle("Foot", parent=BODY, fontSize=8, textColor=colors.HexColor("#666666")),
    )


def build_test_log(out_path: Path | None = None) -> Path:
    """Run pytest and store the raw console output as a PDF."""
    out_path = out_path or (config.EVIDENCE_DIR / f"{config.PACKAGE_NAME}_TEST_LOG.pdf")
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "-v", "--tb=short"],
        cwd=config.PROJECT_ROOT,
        capture_output=True,
        text=True,
    )
    transcript = (result.stdout + "\n" + result.stderr).strip()
    flow = _header_lines("Automated test log (pytest)")
    flow.append(
        Paragraph(
            f"Command: <font face='Courier'>python -m pytest -v --tb=short</font> "
            f"&nbsp;&nbsp;exit code: <b>{result.returncode}</b>",
            BODY,
        )
    )
    flow.append(Spacer(1, 6))
    for line in transcript.splitlines():
        safe = line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;") or "&nbsp;"
        flow.append(Paragraph(safe, MONO))
    flow.append(Spacer(1, 8))
    flow.append(_footer_note())

    out_path.parent.mkdir(parents=True, exist_ok=True)
    SimpleDocTemplate(str(out_path), pagesize=A4, title="AI test log").build(flow)
    return out_path


def build_declaration(out_path: Path | None = None) -> Path:
    """Create the individual-work declaration with a signature line."""
    out_path = out_path or (config.EVIDENCE_DIR / f"{config.PACKAGE_NAME}_DECLARATION.pdf")
    flow = _header_lines("Declaration of individual work")
    flow.append(
        Paragraph(
            "I declare that this assignment is my own individual work. I generated the dataset "
            f"from my own registration digits using seed LLLL = {config.SEED}, wrote or directed the "
            "implementation of the pipeline, ran the experiments reported in the artifacts, and "
            "wrote the interpretations in the report. I have disclosed every use of external tools "
            "and AI assistants in <font face='Courier'>evidence/AI_USE.md</font> and I understand "
            "that I must be able to explain and modify every part of the submitted code.",
            BODY,
        )
    )
    flow.append(Spacer(1, 10))
    flow.append(
        Paragraph(
            "The submission contains only my own synthetic dataset. No real farm records, "
            "personal data, passwords, tokens or private keys are included. The dataset is "
            "explicitly synthetic and the service is a classroom prototype that must not be used "
            "to decide access to finance, insurance or public services.",
            BODY,
        )
    )
    flow.append(Spacer(1, 24))
    flow.append(Paragraph("Name: " + config.FULL_NAME, BODY))
    flow.append(Paragraph("Registration number: " + config.REGISTRATION_NUMBER, BODY))
    flow.append(Paragraph("Verification code: " + config.VERIFICATION_CODE, BODY))
    flow.append(Spacer(1, 26))
    flow.append(Paragraph("Signature: ________________________________________", BODY))
    flow.append(Spacer(1, 14))
    flow.append(Paragraph("Date: __________________", BODY))
    flow.append(Spacer(1, 20))
    flow.append(_footer_note())

    out_path.parent.mkdir(parents=True, exist_ok=True)
    SimpleDocTemplate(str(out_path), pagesize=A4, title="AI declaration").build(flow)
    return out_path


if __name__ == "__main__":
    print(build_test_log())
    print(build_declaration())
